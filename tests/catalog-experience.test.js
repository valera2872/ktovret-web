'use strict';
const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');
const {spawnSync}=require('node:child_process');
const root=path.resolve(__dirname,'..');
const catalog=JSON.parse(fs.readFileSync(path.join(root,'assets/generated/cases-index.json'),'utf8'));
const html=fs.readFileSync(path.join(root,'dela/index.html'),'utf8');
const volume=fs.readFileSync(path.join(root,'tom-1/index.html'),'utf8');
const js=fs.readFileSync(path.join(root,'assets/catalog-experience.js'),'utf8');
const css=fs.readFileSync(path.join(root,'assets/catalog-experience.css'),'utf8');
const storefrontCss=fs.readFileSync(path.join(root,'assets/volume-storefront.css'),'utf8');
const libraryCss=fs.readFileSync(path.join(root,'assets/premium-library.css'),'utf8');
const typographyCss=fs.readFileSync(path.join(root,'assets/typography-polish.css'),'utf8');

assert.equal(catalog.totalCases,110);
assert.equal(catalog.freeCount,10);
assert.equal(catalog.premiumCount,100);
assert.equal(catalog.volume1Count,50);
assert.equal(catalog.volume2Count,50);
assert.equal((html.match(/class="case-card"/g)||[]).length,10,'public catalog must render only 10 free case cards');
assert.equal((html.match(/data-access="free"/g)||[]).length,10,'catalog must render 10 free cards');
assert.equal((html.match(/data-access="premium"/g)||[]).length,0,'premium cases must not appear as a 100-card wall');
assert.ok((html.match(/volume-archive-card/g)||[]).length>0,'premium volume summaries are missing');
assert.ok(html.includes('100 расследований в двух томах'),'two-volume proposition is missing');
assert.ok(html.includes('299 ₽'),'bundle price is missing from catalog');
assert.ok(html.includes('tom-1/?product=volume_bundle_1_2'),'catalog must link to the two-volume offer');
assert.ok(html.includes('data-catalog-progress'),'command center is missing');
assert.ok(html.includes('data-catalog-continue'),'continue action is missing');
assert.ok(html.includes('data-catalog-random'),'random free case action is missing');
assert.ok(html.includes('id="case-difficulty"'),'difficulty filter is missing');
assert.ok(html.includes('id="case-category"'),'category filter is missing');
assert.ok(html.includes('id="case-unsolved"'),'unsolved-only filter is missing');
assert.ok(!html.includes('full-catalog.js?v='),'legacy filter script must not compete with catalog experience');
assert.ok(js.includes('MysteryLogicDossier'),'catalog must read dossier progress');
assert.ok(js.includes("card.dataset.progress=solved?'solved':active?'active':'new'"),'case progress states are missing');
assert.ok(js.includes('pickRandomCase'),'random unsolved selection is missing');
assert.ok(css.includes('.catalog-command'),'command center styling is missing');
assert.ok(css.includes('.case-card.is-solved'),'solved case styling is missing');
assert.ok(volume.includes('100 дел в двух томах'),'two-volume sales headline is missing');
assert.ok(volume.includes('10 полноценных дел доступны бесплатно'),'free-access promise is missing');
assert.ok(volume.includes('data-volume-product="volume1"'),'Volume I selector is missing');
assert.ok(volume.includes('data-volume-product="volume2"'),'Volume II selector is missing');
assert.ok(volume.includes('data-volume-product="volume_bundle_1_2"'),'two-volume bundle selector is missing');
assert.ok(volume.includes('50 дел · 199 ₽'),'single-volume offer is missing');
assert.ok(volume.includes('100 дел · 299 ₽'),'bundle offer is missing');
assert.ok(volume.includes('data-volume-buy disabled'),'payment button must require checkout details before enabling');
assert.ok(!volume.includes('name="robots" content="noindex'),'volume page must be indexable at SEO launch');
assert.ok(volume.includes('rel="canonical"'),'volume page must keep a canonical URL');
assert.ok(volume.includes('support@mysterylogic.com'),'support contact is missing from storefront');
assert.ok((volume.match(/ref-volume-archive-card/g)||[]).length>=3,'volume offer cards are missing');
assert.ok(storefrontCss.includes('.volume-purchase-card'),'compact purchase card styling is missing');
assert.ok(libraryCss.includes('.volume-lock:before'),'premium archive lock styling is missing');
assert.ok(volume.includes('assets/typography-polish.css?v=1.0.0'),'storefront must receive shared typography polish');
assert.ok(typographyCss.includes('.ktv-game-shell .ktv-hero h1'),'typography polish must cover gameplay headings');
assert.ok(typographyCss.includes('.volume-hero h1'),'typography polish must cover storefront headings');

const originSmoke=spawnSync(process.execPath,[path.join(root,'tests/site-origin.test.mjs')],{cwd:root,encoding:'utf8'});
assert.equal(originSmoke.status,0,`site origin 1.9 smoke failed: ${originSmoke.stderr||originSmoke.stdout}`);
assert.ok(originSmoke.stdout.includes('site origin 1.9 smoke passed'),'site origin smoke did not confirm production migration');

